package io.tehred5pade.frontporch.data.innertube

import org.json.JSONObject

/**
 * A caption track advertised by YouTube's player response. [url] points at a WebVTT
 * document that ExoPlayer can load as a normal text track.
 */
data class CaptionTrack(
    val languageCode: String,
    val label: String,
    val url: String,
    val isAutoGenerated: Boolean = false
)

/** Extracts caption tracks from a youtubei/v1/player response. */
fun parseCaptionTracks(root: JSONObject): List<CaptionTrack> {
    val tracks = root.optJSONObject("captions")
        ?.optJSONObject("playerCaptionsTracklistRenderer")
        ?.optJSONArray("captionTracks") ?: return emptyList()

    val parsed = mutableListOf<CaptionTrack>()
    for (i in 0 until tracks.length()) {
        val track = tracks.optJSONObject(i) ?: continue
        val baseUrl = track.optString("baseUrl").ifBlank { continue }
        val languageCode = track.optString("languageCode").ifBlank { continue }

        val name = track.optJSONObject("name")
        val rawLabel = buildString {
            append(name?.optString("simpleText").orEmpty())
            name?.optJSONArray("runs")?.let { runs ->
                for (j in 0 until runs.length()) {
                    append(runs.optJSONObject(j)?.optString("text").orEmpty())
                }
            }
        }.ifBlank { languageCode }

        val isAutoGenerated = track.optString("kind").equals("asr", ignoreCase = true)
        val label = if (isAutoGenerated && !rawLabel.contains("auto", ignoreCase = true)) {
            "$rawLabel (auto-generated)"
        } else {
            rawLabel
        }

        parsed += CaptionTrack(
            languageCode = languageCode,
            label = label,
            url = baseUrl.toVttUrl(),
            isAutoGenerated = isAutoGenerated
        )
    }
    return parsed.distinctBy { it.languageCode to it.label }
}

/** YouTube returns srv3/TTML by default; ExoPlayer parses WebVTT out of the box. */
private fun String.toVttUrl(): String {
    val fmtRegex = Regex("([?&])fmt=[^&]*")
    val replaced = replace(fmtRegex) { match -> match.groupValues[1] + "fmt=vtt" }
    return if (replaced.contains("fmt=")) {
        replaced
    } else {
        replaced + (if (replaced.contains("?")) "&fmt=vtt" else "?fmt=vtt")
    }
}
